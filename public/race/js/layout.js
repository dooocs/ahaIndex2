// 一段带拱桥的直堤：在 (x0,z0)→(x1,z1) 上均匀放 n 座桥，桥顶高 peak
function causeway(x0, z0, x1, z1, n, peak, foot = 24) {
  const pts = [], len = Math.hypot(x1 - x0, z1 - z0);
  const at = (t, y) => [x0 + (x1 - x0) * t, z0 + (z1 - z0) * t, y];
  const half = foot / len;
  for (let b = 0; b < n; b++) {
    const tc = (b + 0.5) / n;
    pts.push(at(tc - 0.5 / n, 0.3), at(tc - half, 0.4), at(tc, peak), at(tc + half, 0.4));
  }
  return pts;
}

