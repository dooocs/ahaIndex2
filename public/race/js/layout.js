// 苏堤：六座拱桥（映波、锁澜、望山、压堤、东浦、跨虹），桥顶 3.2 米。全速过桥会腾空。
export const SUDI_BRIDGES = ['映波桥', '锁澜桥', '望山桥', '压堤桥', '东浦桥', '跨虹桥'];
function causeway(x0, z0, x1, z1, bridges, peak) {
  const pts = [];
  const len = Math.hypot(x1 - x0, z1 - z0);
  const at = (t, y) => [x0 + (x1 - x0) * t, z0 + (z1 - z0) * t, y];
  const half = 24 / len;
  for (let b = 0; b < bridges; b++) {
    const tc = (b + 0.5) / bridges;
    pts.push(at(tc - 0.5 / bridges, 0.3));      // 两桥之间的平路
    pts.push(at(tc - half, 0.4));
    pts.push(at(tc, peak));
    pts.push(at(tc + half, 0.4));
  }
  return pts;
}

